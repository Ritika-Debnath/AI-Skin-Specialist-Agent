from deepgram import DeepgramClient
import os
from pathlib import Path
from dotenv import load_dotenv
load_dotenv()

BASE_DIR = Path(__file__).resolve().parent      # This is the directory where this Python file is located. It helps us create paths for saving files in the same folder as this program.

DEFAULT_DOCTOR_AUDIO = BASE_DIR / "doctor_response.mp3"

def convert_text_to_doctor_audio(text, output_filepath=DEFAULT_DOCTOR_AUDIO):    # This function takes a text string and converts it into an audio file using the Deepgram API. The audio is saved to the specified output file path.
    deepgram_api_key = os.environ.get("DEEPGRAM_API_KEY")
    deepgram = DeepgramClient(api_key=deepgram_api_key)
    audio = deepgram.speak.v1.audio.generate(
        text=text,
        model=os.environ.get("DEEPGRAM_TTS_MODEL", "aura-2-thalia-en"),
        encoding="mp3",
    )

    output_filepath = Path(output_filepath)         # Ensure the output file path is a Path object, which makes it easier to work with file paths in Python.
    with output_filepath.open("wb") as file:
        for chunk in audio:
            file.write(chunk)

    return output_filepath


# THis part of code is for playing the audio file generated by the Deepgram API. It uses different commands based on the operating system to play the audio file.
import subprocess
import platform
def play_audio(audio_filepath):
    audio_filepath = str(audio_filepath)

    if platform.system() == "Darwin":
        subprocess.run(["afplay", audio_filepath], check=False)
    elif platform.system() == "Windows":
        os.startfile(audio_filepath)
    else:
        subprocess.run(["xdg-open", audio_filepath], check=False)


